"""Run the test suite with the cost recorder and write the ranking of what each test costs.

`uv run python scripts/rank_test_costs.py` runs the suite once under `-p
scripts.record_test_costs`, measures the CPU and wall time of the whole run, and writes
`test_organisation/test_cost_ranking.md`. A run with failures exits non-zero and leaves the
ranking as it was, because a ranking of a broken run is not a measurement of the suite.
"""

from __future__ import annotations

import json
import os
import platform
import resource
import subprocess
import sys
from collections import defaultdict
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from time import monotonic
from typing import NamedTuple

# Running the file by path puts scripts/ on sys.path, not the repo root, so `scripts` is not
# importable until the root is added.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.record_test_costs import CostsFile, costs_path

REPO_ROOT = Path(__file__).resolve().parents[1]
COSTS_PATH = costs_path(REPO_ROOT)
RANKING_PATH = REPO_ROOT / "test_organisation" / "test_cost_ranking.md"
PRESSURE_PATH = Path("/proc/pressure/cpu")
PYTEST_COMMAND: list[str] = [
    sys.executable,
    "-m",
    "pytest",
    "-p",
    "scripts.record_test_costs",
    "-p",
    "no:randomly",
    "-n",
    "4",
    "--no-cov",
    "-m",
    "not ci_only and not weasyprint and not playwright",
    "--ignore=freedom_ls/educator_interface/tests/invariants/test_permission_matrix.py",
    "--ignore=tests/test_rank_test_costs.py",
]
TOP_FILES = 50
TOP_FUNCTIONS = 200
FIRST_LINE = (
    "Generated by uv run python scripts/rank_test_costs.py. Do not edit by hand."
)


class PytestRun(NamedTuple):
    returncode: int
    cpu_seconds: float  # RUSAGE_CHILDREN user + sys, after minus before
    wall_seconds: float


@dataclass(frozen=True)
class RunInfo:
    """Everything the header needs that the costs file does not hold."""

    date: str
    commit: str
    cpu_seconds: float
    wall_seconds: float
    conditions: tuple[str, ...]


@dataclass(frozen=True)
class Group:
    """The tests that share one key, summed."""

    key: str
    count: int
    seconds: float
    setup_seconds: float


def function_key(nodeid: str) -> str:
    # Paths and function names hold no "[", so the first one opens the parameter id, which
    # may itself hold "::" or "[".
    return nodeid.split("[", 1)[0]


def file_key(nodeid: str) -> str:
    return nodeid.split("::")[0]


def area_of(nodeid: str) -> str:
    """freedom_ls/<app> and claude_plugins/<plugin> are areas; tests/ is one area."""
    parts = file_key(nodeid).split("/")
    return (
        "/".join(parts[:2])
        if parts[0] in {"freedom_ls", "claude_plugins"}
        else parts[0]
    )


def group_costs(costs: CostsFile, key_of: Callable[[str], str]) -> list[Group]:
    """Groups sorted by rounded seconds, descending, then by key."""
    counts: dict[str, int] = defaultdict(int)
    seconds: dict[str, float] = defaultdict(float)
    setup_seconds: dict[str, float] = defaultdict(float)
    for nodeid, phases in costs["tests"].items():
        key = key_of(nodeid)
        counts[key] += 1
        seconds[key] += phases["setup"] + phases["call"] + phases["teardown"]
        setup_seconds[key] += phases["setup"]
    groups = [
        Group(key, counts[key], seconds[key], setup_seconds[key]) for key in counts
    ]
    return sorted(groups, key=lambda group: (-round(group.seconds, 1), group.key))


def percent(part: float, whole: float) -> str:
    return f"{round(100 * part / whole) if whole else 0}%"


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = [f"| {' | '.join(header)} |", f"|{'---|' * len(header)}"]
    lines.extend(f"| {' | '.join(row)} |" for row in rows)
    return lines


def share_rows(groups: list[Group], total: float) -> list[list[str]]:
    return [
        [g.key, str(g.count), f"{g.seconds:.1f}", percent(g.seconds, total)]
        for g in groups
    ]


def function_rows(groups: list[Group], total: float) -> list[list[str]]:
    rows: list[list[str]] = []
    cumulative = 0.0
    for group in groups:
        cumulative += group.seconds
        rows.append(
            [
                group.key,
                str(group.count),
                f"{group.seconds:.1f}",
                f"{group.seconds / group.count:.1f}",
                percent(group.setup_seconds, group.seconds),
                percent(group.seconds, total),
                percent(cumulative, total),
            ]
        )
    return rows


def render_ranking(
    costs: CostsFile,
    run: RunInfo,
    top_files: int = TOP_FILES,
    top_functions: int = TOP_FUNCTIONS,
) -> str:
    areas = group_costs(costs, area_of)
    total = sum(area.seconds for area in areas)
    db_setup = costs["django_db_setup"]
    lines = [
        FIRST_LINE,
        "",
        "# Test cost ranking",
        "",
        f"- Date: {run.date}",
        f"- Commit: {run.commit}",
        f"- Tests: {costs['test_count']}",
        f"- CPU seconds: {run.cpu_seconds:.1f}",
        f"- Wall seconds: {run.wall_seconds:.1f}",
        f"- Summed test cost: {total:.1f} seconds",
        f"- Database setup: {sum(db_setup.values()):.1f} seconds across {len(db_setup)} workers",
        "- Run conditions:",
        *(f"  - {condition}" for condition in run.conditions),
        "",
        "## Areas",
        "",
        *table(["Area", "Tests", "Seconds", "Share"], share_rows(areas, total)),
        "",
        f"## Top {top_files} files",
        "",
        *table(
            ["File", "Tests", "Seconds", "Share"],
            share_rows(group_costs(costs, file_key)[:top_files], total),
        ),
        "",
        f"## Top {top_functions} functions",
        "",
        *table(
            [
                "Function",
                "Cases",
                "Seconds",
                "Mean per case",
                "Setup share",
                "Share",
                "Cumulative share",
            ],
            function_rows(group_costs(costs, function_key)[:top_functions], total),
        ),
    ]
    return "\n".join(lines) + "\n"


def run_pytest(command: list[str]) -> PytestRun:
    """Run the command from the repo root, with the root on PYTHONPATH so `-p` can import the
    recorder, and measure the CPU its whole process tree used."""
    before = resource.getrusage(resource.RUSAGE_CHILDREN)
    start = monotonic()
    completed = subprocess.run(
        command,
        cwd=REPO_ROOT,
        env={**os.environ, "PYTHONPATH": str(REPO_ROOT)},
    )
    wall = monotonic() - start
    after = resource.getrusage(resource.RUSAGE_CHILDREN)
    cpu = (after.ru_utime + after.ru_stime) - (before.ru_utime + before.ru_stime)
    return PytestRun(completed.returncode, cpu, wall)


def git_output(*args: str) -> str:
    # git is looked up on PATH, like any developer tool.
    return subprocess.run(
        ["git", *args],  # noqa: S607
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()


def commit_label() -> str:
    """The HEAD SHA, with `-dirty` when tracked files differ from it."""
    dirty = git_output("status", "--porcelain", "--untracked-files=no")
    return git_output("rev-parse", "HEAD") + ("-dirty" if dirty else "")


def cpu_pressure() -> str:
    """The `some avg60` figure of /proc/pressure/cpu, or `n/a` where the kernel has none."""
    try:
        first_line = PRESSURE_PATH.read_text().splitlines()[0]
    except (OSError, IndexError):
        return "n/a"
    fields = dict(
        field.split("=", 1) for field in first_line.split()[1:] if "=" in field
    )
    return fields.get("avg60", "n/a")


def load_condition(moment: str) -> str:
    one, five, fifteen = os.getloadavg()
    return (
        f"Load average at {moment}: {one:.2f} {five:.2f} {fifteen:.2f}; "
        f"CPU pressure avg60 at {moment}: {cpu_pressure()}"
    )


def main(command: list[str] | None = None, output: Path | None = None) -> int:
    COSTS_PATH.unlink(missing_ok=True)  # a stale file must never be ranked
    command = command if command is not None else PYTEST_COMMAND
    start_load = load_condition("start")
    run = run_pytest(command)
    end_load = load_condition("end")
    if run.returncode != 0:
        print(
            f"The ranking run exited with {run.returncode}; the ranking is left as it was.",
            file=sys.stderr,
        )
        return run.returncode
    if not COSTS_PATH.exists():
        print(f"The run wrote no costs file at {COSTS_PATH}.", file=sys.stderr)
        return 1
    costs: CostsFile = json.loads(COSTS_PATH.read_text())
    info = RunInfo(
        date=datetime.now(UTC).date().isoformat(),
        commit=commit_label(),
        cpu_seconds=run.cpu_seconds,
        wall_seconds=run.wall_seconds,
        conditions=(
            f"pytest arguments: {' '.join(command[3:])}",
            f"Python: {platform.python_version()}",
            f"CPUs: {os.cpu_count()}",
            start_load,
            end_load,
        ),
    )
    target = output if output is not None else RANKING_PATH
    target.write_text(render_ranking(costs, info))
    print(
        f"Wrote {target}: {costs['test_count']} tests, "
        f"{run.cpu_seconds:.1f} CPU seconds, {run.wall_seconds:.1f} wall seconds."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())

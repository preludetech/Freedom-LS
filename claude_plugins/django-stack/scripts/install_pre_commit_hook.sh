#!/usr/bin/env bash
# Usage: install_pre_commit_hook.sh   (run from anywhere inside the repository)
#
# Writes the repository's pre-commit hook as a shim that runs pre-commit from the committing
# worktree's own uv environment. `pre-commit install` bakes one worktree's venv path into the
# hook, which every worktree shares, so the hook breaks once that worktree is deleted. The shim
# also lets a plain `git commit` run the hooks, which matters where Claude Code refuses
# `uv run git commit` (a session after EnterWorktree, or an `isolation: "worktree"` sub-agent).
#
# Overwrites only a missing hook, one generated by pre-commit, or its own earlier copy. Any
# other hook is left alone and the script exits 1 naming it.
set -euo pipefail

marker="Installed by django-stack install_pre_commit_hook.sh"
hook="$(git rev-parse --path-format=absolute --git-path hooks/pre-commit)"

if [ -e "$hook" ] && ! grep -q -e "$marker" -e "File generated by pre-commit" "$hook"; then
    echo "Left $hook alone: it is a custom hook, not one pre-commit or this script wrote." >&2
    exit 1
fi

mkdir -p "$(dirname "$hook")"
cat > "$hook" <<SHIM
#!/usr/bin/env bash
# $marker
root="\$(git rev-parse --show-toplevel)"
exec uv run --project "\$root" pre-commit hook-impl --config=.pre-commit-config.yaml \\
    --hook-type=pre-commit --hook-dir "\$(cd "\$(dirname "\$0")" && pwd)" -- "\$@"
SHIM
chmod +x "$hook"
echo "Pre-commit hook installed: $hook"

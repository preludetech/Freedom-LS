def _ensure_logo(organisation: Organisation) -> None:
    if not organisation.logo:
        with LOGO_PATH.open("rb") as fh:
            organisation.logo.save(LOGO_PATH.name, File(fh), save=True)


def _get_or_create_lesson(site: Site, course: DemoCourse, index: int) -> Topic:
    lesson = cast(Lesson, course.items[index])
    slug = f"{course.slug}-lesson-{index + 1:02d}"
    existing: Topic | None = Topic.objects.filter(slug=slug, site=site).first()
    if existing is not None:
        return existing
    return cast(
        Topic,
        TopicFactory(title=lesson.title, slug=slug, content=lesson.content, site=site),
    )


def _get_or_create_quiz(site: Site, course: DemoCourse, index: int) -> Form:
    quiz = cast(Quiz, course.items[index])
    slug = f"{course.slug}-quiz-{index + 1:02d}"
    existing: Form | None = Form.objects.filter(slug=slug, site=site).first()
    if existing is not None:
        return existing
    form = cast(
        Form,
        FormFactory(
            title=quiz.title,
            slug=slug,
            strategy=FormStrategy.QUIZ,
            quiz_show_incorrect=True,
            quiz_pass_percentage=PASS_PERCENTAGE,
            site=site,
        ),
    )
    page = cast(
        FormPage,
        FormPageFactory(
            form=form, title=quiz.title, slug=f"{slug}-page", order=0, site=site
        ),
    )
    for order, question in enumerate(quiz.questions):
        is_checkbox = sum(correct for _, correct in question.options) > 1
        form_question = cast(
            FormQuestion,
            FormQuestionFactory(
                form_page=page,
                question=question.text,
                type=(
                    QuestionType.CHECKBOXES
                    if is_checkbox
                    else QuestionType.MULTIPLE_CHOICE
                ),
                required=True,
                order=order,
                site=site,
            ),
        )
        _add_options(form_question, list(question.options), site)
    return form


def _build_course(site: Site, course: DemoCourse) -> Course:
    existing: Course | None = Course.objects.filter(slug=course.slug, site=site).first()
    course_row = existing or cast(
        Course,
        CourseFactory(
            title=course.title,
            slug=course.slug,
            description=course.description,
            site=site,
        ),
    )
    plan: list[Topic | Form] = [
        _get_or_create_quiz(site, course, index)
        if isinstance(item, Quiz)
        else _get_or_create_lesson(site, course, index)
        for index, item in enumerate(course.items)
    ]
    _lay_out_course(course_row, plan, site)
    return course_row


def _render_report(cohort: Cohort, requested_by: User, output_dir: Path) -> Path:
    report = GeneratedReport.objects.create(
        cohort=cohort, site_id=cohort.site_id, requested_by=requested_by
    )
    generate_cohort_report(str(report.pk), cohort.site_id)
    report.refresh_from_db()
    if report.status != GeneratedReport.STATUS_READY:
        raise click.ClickException(
            f"Report for {cohort.name!r} failed: {report.error_message}"
        )
    destination = output_dir / f"Drone-X - {cohort.name}.pdf"
    with report.file.open("rb") as fh:
        destination.write_bytes(fh.read())
    return destination


@click.command()
@click.option(
    "--site-name",
    default="DemoDev",
    help="Site name to create the data on (default: 'DemoDev').",
)
@click.option(
    "--output-dir",
    default="qa-artifacts/dronex",
    type=click.Path(file_okay=False, path_type=Path),
    help="Where to save the rendered PDFs (default: qa-artifacts/dronex).",
)
@click.option(
    "--no-render",
    is_flag=True,
    default=False,
    help="Build the data only; generate the reports from the admin instead.",
)
def command(site_name: str, output_dir: Path, no_render: bool) -> None:
    """Build the Drone-X demo organisation, courses and cohorts, and render reports."""
    site = _get_site(site_name)

    organisation, _ = ensure_organisation(
        site, ORGANISATION_NAME, slug_base=ORGANISATION_SLUG
    )
    _ensure_logo(organisation)
    click.secho(
        f"Organisation: {organisation.name} (slug={organisation.slug})",
        fg="cyan",
        bold=True,
    )

    for course in DEMO_COURSES:
        _build_course(site, course)
        click.secho(f"  Course: {course.title}", fg="green")

    manager = _get_or_create_user(
        site, MANAGER_EMAIL, MANAGER_FIRST_NAME, MANAGER_LAST_NAME
    )
    _grant_report_admin_access(manager)
    _pin_current_site(site)
    with _site_context(site):
        assign_object_role(manager, organisation, "organisation_admin")

    cohorts: list[Cohort] = []
    for demo_cohort in DEMO_COHORTS:
        cohort = build_report_cohort(
            site=site,
            cohort_name=demo_cohort.name,
            num_learners=demo_cohort.num_learners,
            course_slugs=demo_cohort.course_slugs,
            inactive_course_slugs=(),
            num_flagged=demo_cohort.num_flagged,
            no_progress=False,
            email_prefix=demo_cohort.email_prefix,
            educator_email=None,
            organisation=organisation,
        )
        cohorts.append(cohort)
        click.secho(
            f"  Cohort: {cohort.name} ({demo_cohort.num_learners} learners)",
            fg="green",
        )

    click.secho(
        f"Training manager: {MANAGER_EMAIL} / {MANAGER_EMAIL} "
        f"(staff, organisation_admin on {organisation.name})",
        fg="cyan",
    )

    if no_render:
        return

    output_dir.mkdir(parents=True, exist_ok=True)
    with _site_context(site):
        for cohort in cohorts:
            path = _render_report(cohort, manager, output_dir)
            click.secho(f"  Report: {path}", fg="green", bold=True)

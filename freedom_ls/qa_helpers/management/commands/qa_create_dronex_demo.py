"""Build a Drone-X branded demo and render its cohort progress reports to PDF.

A sales demo, not a QA matrix: the organisation carries Drone-X's own logo, the
courses are drone-pilot training with real quiz questions, and two cohorts
carry a believable spread of progress, quiz scores and at-risk learners. The
generic ``qa-report-*`` courses read "Voltage Q01 option A (correct)", which is
fine for checking layout and useless in front of a customer.

Learner progress is generated by ``build_report_cohort``, the same builder the
report QA matrix uses, so the demo exercises every section of the report.

Each run renders a fresh report per cohort through ``generate_cohort_report``,
synchronously, and copies the PDF into ``--output-dir``. The reports are also
listed in the admin, where the training manager can download them.

Idempotent apart from the reports: courses, cohorts and learners are reused.

Usage:
    uv run python manage.py qa_create_dronex_demo
    uv run python manage.py qa_create_dronex_demo --output-dir qa-artifacts/dronex
    uv run python manage.py qa_create_dronex_demo --no-render
"""


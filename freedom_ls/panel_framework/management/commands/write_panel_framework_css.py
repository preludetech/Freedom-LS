"""Generate ``tailwind.panel_framework.css`` at the project root.

The file points the host's Tailwind build at the installed panel framework: an
``@source`` for its templates, so the utility classes they use are emitted, and
an ``@import`` of its stylesheet, so its rules pass through the host's own
Tailwind run and resolve against the host's theme tokens. Run it before each
Tailwind build and after installing or upgrading the framework, because the
paths it writes are machine-specific.
"""

from __future__ import annotations

from pathlib import Path

from django.apps import apps
from django.conf import settings
from django.core.management.base import BaseCommand

GENERATED_FILE_NAME = "tailwind.panel_framework.css"

HEADER = (
    "/* Generated by manage.py write_panel_framework_css. Do not edit by hand.\n"
    "   Re-run after installing or upgrading the panel framework: "
    "the paths are machine-specific. */\n"
)


def _css_path(target: Path, base_dir: Path) -> str:
    """`./relative` inside base_dir, absolute outside it. Both POSIX."""
    try:
        return "./" + target.relative_to(base_dir).as_posix()
    except ValueError:
        return target.as_posix()


class Command(BaseCommand):
    help = "Write tailwind.panel_framework.css for the installed panel framework."

    def handle(self, *args: object, **options: object) -> None:
        base_dir = Path(settings.BASE_DIR)
        app_dir = Path(apps.get_app_config("freedom_ls_panel_framework").path)
        content = HEADER + (
            f'@source "{_css_path(app_dir / "templates", base_dir)}";\n'
            f'@import "{_css_path(app_dir / "css" / "panel_framework.css", base_dir)}";\n'
        )
        target = base_dir / GENERATED_FILE_NAME
        # Tailwind's watcher rebuilds on any write, so an unchanged file is left alone.
        if not target.exists() or target.read_text() != content:
            target.write_text(content)
        self.stdout.write(str(target))

"""Tests for the write_panel_framework_css management command."""

from __future__ import annotations

import os
from io import StringIO
from pathlib import Path

import pytest
import pytest_django.fixtures

from django.apps import apps
from django.core.management import call_command

APP_LABEL = "freedom_ls_panel_framework"
FILE_NAME = "tailwind.panel_framework.css"


def _run() -> str:
    out = StringIO()
    call_command("write_panel_framework_css", stdout=out)
    return out.getvalue()


@pytest.fixture
def base_dir(tmp_path: Path, settings: pytest_django.fixtures.SettingsWrapper) -> Path:
    settings.BASE_DIR = tmp_path
    return tmp_path


def test_writes_base_dir_relative_paths_for_an_app_inside_base_dir(
    base_dir: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(
        apps.get_app_config(APP_LABEL), "path", str(base_dir / "vendor/pf")
    )

    _run()

    assert (base_dir / FILE_NAME).read_text().splitlines()[2:] == [
        '@source "./vendor/pf/templates";',
        '@import "./vendor/pf/css/panel_framework.css";',
    ]


def test_writes_absolute_paths_for_an_app_outside_base_dir(
    base_dir: Path,
    tmp_path_factory: pytest.TempPathFactory,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    outside = tmp_path_factory.mktemp("site_packages") / "pf"
    monkeypatch.setattr(apps.get_app_config(APP_LABEL), "path", str(outside))

    _run()

    assert (base_dir / FILE_NAME).read_text().splitlines()[2:] == [
        f'@source "{outside.as_posix()}/templates";',
        f'@import "{outside.as_posix()}/css/panel_framework.css";',
    ]


def test_opens_with_a_do_not_edit_header(base_dir: Path) -> None:
    _run()

    assert (
        (base_dir / FILE_NAME)
        .read_text()
        .startswith(
            "/* Generated by manage.py write_panel_framework_css. Do not edit by hand."
        )
    )


def test_a_second_run_leaves_the_file_untouched(base_dir: Path) -> None:
    _run()
    target = base_dir / FILE_NAME
    os.utime(target, ns=(1_000_000_000, 1_000_000_000))

    _run()

    assert target.stat().st_mtime_ns == 1_000_000_000


def test_prints_the_path_it_wrote(base_dir: Path) -> None:
    assert _run().strip() == str(base_dir / FILE_NAME)

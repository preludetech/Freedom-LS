"""`install_pre_commit_hook.sh` writes a pre-commit hook that works from every worktree."""

from __future__ import annotations

from pathlib import Path

import pytest

from tests._script_trees import run_command

pytestmark = pytest.mark.dev_tooling

REPO_ROOT = Path(__file__).resolve().parents[1]
SCRIPT = (
    REPO_ROOT
    / "claude_plugins"
    / "django-stack"
    / "scripts"
    / "install_pre_commit_hook.sh"
)
SHIM_MARKER = "Installed by django-stack install_pre_commit_hook.sh"


def git_repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    repo.mkdir()
    run_command(["git", "init", "-q"], repo)
    return repo


def hook_path(repo: Path) -> Path:
    return repo / ".git" / "hooks" / "pre-commit"


def test_writes_executable_shim_when_no_hook_exists(tmp_path: Path) -> None:
    repo = git_repo(tmp_path)

    result = run_command(["bash", str(SCRIPT)], repo)

    assert result.returncode == 0
    hook = hook_path(repo)
    assert SHIM_MARKER in hook.read_text(encoding="utf-8")
    assert "git rev-parse --show-toplevel" in hook.read_text(encoding="utf-8")
    assert hook.stat().st_mode & 0o111


def test_replaces_a_hook_generated_by_pre_commit(tmp_path: Path) -> None:
    repo = git_repo(tmp_path)
    hook = hook_path(repo)
    hook.parent.mkdir(parents=True, exist_ok=True)
    hook.write_text(
        "#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\n"
        "INSTALL_PYTHON=/gone/.venv/bin/python\n",
        encoding="utf-8",
    )

    result = run_command(["bash", str(SCRIPT)], repo)

    assert result.returncode == 0
    assert SHIM_MARKER in hook.read_text(encoding="utf-8")
    assert "/gone/" not in hook.read_text(encoding="utf-8")


def test_running_twice_leaves_the_shim_in_place(tmp_path: Path) -> None:
    repo = git_repo(tmp_path)
    run_command(["bash", str(SCRIPT)], repo)

    result = run_command(["bash", str(SCRIPT)], repo)

    assert result.returncode == 0
    assert SHIM_MARKER in hook_path(repo).read_text(encoding="utf-8")


def test_refuses_to_overwrite_a_custom_hook(tmp_path: Path) -> None:
    repo = git_repo(tmp_path)
    hook = hook_path(repo)
    hook.parent.mkdir(parents=True, exist_ok=True)
    hook.write_text("#!/bin/sh\necho mine\n", encoding="utf-8")

    result = run_command(["bash", str(SCRIPT)], repo)

    assert result.returncode == 1
    assert "echo mine" in hook.read_text(encoding="utf-8")
    assert str(hook) in result.stderr
